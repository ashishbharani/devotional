"""Import explicitly reviewed translations into local packs, never automatically publish.

The review JSON is generated by export_translation_review.py. Only records
marked 'approved' and attributed to a reviewer may be imported. By default
this command is a dry run. No source texts or existing translations are edited.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

from audit_hosted_translations import CODES, ROOT, norm

PROTECTED = re.compile(
    r"https?://[^\s<>\"']+|[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|"
    r"\{\{[^{}]+\}\}|\$\{[^{}]+\}|\{[A-Za-z_][A-Za-z0-9_]*\}"
)


def sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def stage_review(review: dict, report: dict, packs: dict) -> tuple[dict, dict]:
    """Validate all entries before changing any pack; return staged copies."""
    if review.get("schema") != 1 or not isinstance(report.get("backlog"), list):
        raise ValueError("Invalid review schema or coverage report")
    expected = {row["id"]: row for row in report["backlog"]}
    records = review.get("records")
    if not isinstance(records, list) or len(records) != len(expected):
        raise ValueError("Review records differ from the audited inventory")
    staged = {code: dict(pack["translations"]) for code, pack in packs.items()}
    counts = {code: 0 for code in CODES}
    seen = set()
    for row in records:
        if not isinstance(row, dict) or row.get("id") not in expected:
            raise ValueError("Unknown review record")
        item = expected[row["id"]]
        if row["id"] in seen:
            raise ValueError("Duplicate review record")
        seen.add(row["id"])
        source = item["source"]
        if row.get("source") != source or row.get("missingLanguages") != item["languages"]:
            raise ValueError("Changed source or missing-language list: " + row["id"])
        values = row.get("translations")
        if not isinstance(values, dict) or set(values) != set(item["languages"]):
            raise ValueError("Unexpected translation language or missing translation cell")
        status = row.get("reviewStatus")
        if status not in ("approved", "unreviewed", "rejected", "needs-revision"):
            raise ValueError("Invalid review status for " + row["id"])
        if status != "approved":
            if any(values.values()):
                raise ValueError("Unapproved translations cannot be imported: " + row["id"])
            continue
        if not isinstance(row.get("reviewer"), str) or not row["reviewer"].strip():
            raise ValueError("Approved record needs a named reviewer: " + row["id"])
        if not any(isinstance(value, str) and value.strip() for value in values.values()):
            raise ValueError("Approved record has no translations: " + row["id"])
        for code, value in values.items():
            if value == "":
                continue  # Sequential review of one language at a time is allowed.
            if not isinstance(value, str) or not value.strip() or norm(value) == norm(source):
                raise ValueError("Empty/unchanged translation for " + row["id"] + "/" + code)
            for token in PROTECTED.findall(source):
                if token not in value:
                    raise ValueError("Protected URL/email/template token lost in " + row["id"] + "/" + code)
            existing = staged[code].get(source)
            if existing is not None and existing != value:
                raise ValueError("Existing translation would be overwritten: " + row["id"] + "/" + code)
            if existing is None:
                # Reject normalized duplicate keys even if their spelling differs.
                if any(norm(key) == norm(source) for key in staged[code]):
                    raise ValueError("Normalized source key collision: " + row["id"])
                staged[code][source] = value
                counts[code] += 1
    return staged, counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--review", required=True, type=Path)
    parser.add_argument("--audit", type=Path, default=ROOT / "work/translation-coverage.json")
    parser.add_argument("--apply", action="store_true", help="Write reviewed entries to content packs")
    args = parser.parse_args()

    review_bytes = args.review.read_bytes()
    review = json.loads(review_bytes)
    report_bytes = args.audit.read_bytes()
    report = json.loads(report_bytes)
    collection_bytes = (ROOT / "data/collection.json").read_bytes()
    i18n_bytes = (ROOT / "docs/assets/i18n.json").read_bytes()
    if (review.get("auditSha256") != sha256(report_bytes)
            or review.get("catalogueSha256") != sha256(collection_bytes)
            or review.get("auditInputs") != report.get("inputs")
            or report.get("inputs", {}).get("catalogueSha256") != sha256(collection_bytes)
            or report.get("inputs", {}).get("i18nSha256") != sha256(i18n_bytes)):
        raise ValueError("Stale translation review; rebuild site, re-audit and re-export")

    files = {code: ROOT / "docs/assets/translations" / (code + ".json") for code in CODES}
    packs = {code: json.loads(path.read_text(encoding="utf-8")) for code, path in files.items()}
    for code, pack in packs.items():
        if pack.get("language") != code or not isinstance(pack.get("translations"), dict):
            raise ValueError("Invalid local translation pack: " + code)
    staged, counts = stage_review(review, report, packs)
    print("Review import:", "apply" if args.apply else "dry run")
    for code in CODES:
        print(f"  {code}: {counts[code]} reviewed units to add")
    if args.apply:
        # All entries have been checked, including collision and provenance checks.
        for code in CODES:
            if counts[code]:
                packs[code]["translations"] = staged[code]
                files[code].write_text(
                    json.dumps(packs[code], ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8",
                )
        print("Reviewed content packs updated; completeness still requires the strict audit.")
    else:
        print("No files changed. Re-run with --apply after reviewing the proposed counts.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
